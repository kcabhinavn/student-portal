#include <cmath>

int sine(int angle) {
  return sin(angle);
}

int cosine(int angle) {
  return cos(angle);
}

int tangent(int angle) {
  return tan(angle);
}
int cosecant(int angle) {
  return 1 / sin(angle);
}

int cotangent(int angle) {
  return 1 / tan(angle);
}

int secant(int angle) {
  return 1 / cos(angle);
}